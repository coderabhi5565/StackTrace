CREATE SEQUENCE post_sequence START WITH 1 INCREMENT BY 50;
CREATE SEQUENCE tag_sequence START WITH 1 INCREMENT BY 20;

CREATE TABLE tags (
    id          BIGINT PRIMARY KEY,
    name        VARCHAR(50) NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_tag_name UNIQUE (name)
);

CREATE TABLE posts (
    id                    BIGINT PRIMARY KEY,
    title                 VARCHAR(250) NOT NULL,
    slug                  VARCHAR(300) NOT NULL,
    content               TEXT         NOT NULL,
    cover_image_url       VARCHAR(500),
    status                VARCHAR(20)  NOT NULL,
    author_id             BIGINT       NOT NULL,
    published_at          TIMESTAMP(6) WITH TIME ZONE,
    deleted_at            TIMESTAMP(6) WITH TIME ZONE,
    excerpt               VARCHAR(300),
    reading_time          INTEGER      NOT NULL DEFAULT 1,
    like_count            INTEGER      NOT NULL DEFAULT 0,
    comment_count         INTEGER      NOT NULL DEFAULT 0,
    scheduled_publish_at  TIMESTAMP(6) WITH TIME ZONE,
    created_at            TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at            TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    -- full-text search document, maintained by Postgres (not mapped by JPA)
    search_vector         TSVECTOR GENERATED ALWAYS AS (
        setweight(to_tsvector('english', coalesce(title, '')), 'A') ||
        setweight(to_tsvector('english', coalesce(excerpt, '')), 'B') ||
        setweight(to_tsvector('english', coalesce(content, '')), 'C')
    ) STORED,
    CONSTRAINT uk_post_slug UNIQUE (slug),
    CONSTRAINT ck_post_status CHECK (status IN ('DRAFT', 'SCHEDULED', 'PUBLISHED'))
);

CREATE TABLE post_tag (
    post_id  BIGINT NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
    tag_id   BIGINT NOT NULL REFERENCES tags (id) ON DELETE CASCADE,
    PRIMARY KEY (post_id, tag_id)
);

CREATE TABLE post_likes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id     BIGINT NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
    user_id     BIGINT NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_post_like UNIQUE (post_id, user_id)
);

CREATE TABLE bookmarks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL,
    post_id     BIGINT NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_bookmark UNIQUE (user_id, post_id)
);
