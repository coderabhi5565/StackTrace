CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username    VARCHAR(30)  NOT NULL,
    name        VARCHAR(100),
    email       VARCHAR(255) NOT NULL,
    bio         VARCHAR(500),
    avatar_url  VARCHAR(255),
    location    VARCHAR(100),
    points      INTEGER      NOT NULL DEFAULT 0,
    created_at  TIMESTAMP(6),
    password    VARCHAR(255) NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email)
);
-- case-insensitive uniqueness for usernames
CREATE UNIQUE INDEX uk_users_username_lower ON users (LOWER(username));

CREATE TABLE user_followers (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    follower_id   BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    following_id  BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at    TIMESTAMP(6),
    CONSTRAINT uk_follow_pair UNIQUE (follower_id, following_id)
);

CREATE TABLE skills (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    skill_name  VARCHAR(100) NOT NULL,
    created_at  TIMESTAMP(6),
    CONSTRAINT uk_skill_user_name UNIQUE (user_id, skill_name)
);

CREATE TABLE badges (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(100) NOT NULL,
    description       VARCHAR(255) NOT NULL,
    icon              VARCHAR(50),
    points_threshold  INTEGER,
    CONSTRAINT uk_badges_name UNIQUE (name)
);

CREATE TABLE user_badges (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    badge_id   BIGINT NOT NULL REFERENCES badges (id) ON DELETE CASCADE,
    earned_at  TIMESTAMP(6),
    CONSTRAINT uk_user_badge UNIQUE (user_id, badge_id)
);

CREATE TABLE refresh_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash  VARCHAR(64) NOT NULL,
    expires_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    revoked_at  TIMESTAMP(6) WITH TIME ZONE,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_refresh_token_hash UNIQUE (token_hash)
);
